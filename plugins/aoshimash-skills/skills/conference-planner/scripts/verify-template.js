#!/usr/bin/env node
/*
 * Mechanical verification for a filled schedule HTML.
 *
 *   node verify-template.js path/to/schedule.html
 *
 * Exits non-zero on any failure. Run this before delivering a generated
 * schedule — a stray backtick renders a blank page, and a mechanical rename
 * across CSS and template strings breaks styling quietly.
 *
 * Where a runtime is unavailable, ../references/mobile-html.md ("Verification")
 * describes the same checks to perform by hand.
 *
 * Class checking works by RUNNING the template's pure string builders and
 * harvesting classes from their real output. Regex-scanning the source instead
 * produces false positives on JS concatenation and misses classes applied via
 * className assignment.
 *
 * TRUST BOUNDARY: this evaluates the target file's inline script, which is the
 * point — parse errors and render output cannot be checked otherwise. Run it
 * only on schedules generated by this skill. Never point it at an HTML file
 * from an untrusted source; that is equivalent to executing it.
 */
"use strict";
const fs = require("fs");

const path = process.argv[2];
if (!path) {
  console.error("usage: node verify-template.js <schedule.html>");
  process.exit(2);
}
const html = fs.readFileSync(path, "utf8");

let failures = 0;
function check(label, pass, detail) {
  if (!pass) failures++;
  console.log((pass ? "PASS  " : "FAIL  ") + label + (detail ? " — " + detail : ""));
}

const script = (html.match(/<script>([\s\S]*?)<\/script>/) || [])[1];
const css = (html.match(/<style>([\s\S]*?)<\/style>/) || [])[1];
if (!script || !css) {
  console.error("no inline <script> or <style> found — is this a filled template?");
  process.exit(2);
}

/* ---- 1. the script body parses ---- */
try {
  new Function(script);
  check("script parses", true);
} catch (e) {
  check("script parses", false, e.message);
}

/* ---- 2. classes emitted vs. classes declared ----
   Everything before the first document access is DOM-free, so the builders can
   be called directly and their output inspected. */
let api = null;
try {
  api = new Function(
    script.split('document.getElementById("evname")')[0] +
    "return { DAYS:DAYS, UI:UI, FLOORS:FLOORS, GLOSSARY:GLOSSARY, PREP:PREP," +
    "  card:card, transitionRow:transitionRow," +
    "  renderDay:renderDay, glossaryHtml:glossaryHtml, prepHtml:prepHtml," +
    "  open:function(id){ openIds[id] = true; } };"
  )();
} catch (e) {
  check("data blocks and builders evaluate", false, e.message);
}

if (api) {
  let rendered = "";
  api.DAYS.forEach(function (day, di) {
    rendered += api.renderDay(day);
    day.items.forEach(function (item, i) {
      const id = "v-" + di + "-" + i;
      ["", "now", "past"].forEach(function (state) {
        rendered += api.card(item, state, id);
      });
      api.open(id);
      rendered += api.card(item, "", id);          // expanded variant
    });
  });
  rendered += api.transitionRow("1F", "3F", 5) + api.transitionRow("1F", "3F", 30);
  rendered += api.glossaryHtml() + api.prepHtml();

  const declared = new Set(
    [...css.matchAll(/\.([a-zA-Z][\w-]*)/g)].map(m => m[1]));
  const used = new Set();
  for (const m of rendered.matchAll(/class="([^"]*)"/g))
    for (const t of m[1].trim().split(/\s+/)) if (t) used.add(t);
  // static markup and buildTabs: leading literal tokens only, so the match
  // stops before any JS concatenation
  for (const m of html.matchAll(/class="([a-zA-Z][\w-]*(?:\s+[a-zA-Z][\w-]*)*)/g))
    for (const t of m[1].split(/\s+/)) if (t) used.add(t);
  // className assignments: operand literals only, so selector arguments to
  // querySelector/getAttribute in the same statement are not counted
  for (const m of script.matchAll(/\.className\s*=\s*([^;]+);/g))
    for (const lit of m[1].matchAll(/[=+?:]\s*"([^"]*)"/g))
      for (const t of lit[1].trim().split(/\s+/))
        if (/^[a-zA-Z][\w-]*$/.test(t)) used.add(t);

  const missing = [...used].filter(c => !declared.has(c));
  check("every emitted class exists in CSS", missing.length === 0, missing.join(", "));
  const dead = [...declared].filter(c => !used.has(c));
  check("no dead CSS classes", dead.length === 0, dead.join(", "));

  /* ---- 3. data integrity ---- */
  const badFloor = [], badTime = [];
  api.DAYS.forEach(function (day) {
    day.items.forEach(function (item, i) {
      if (!(item.f in api.FLOORS)) badFloor.push(day.id + ": " + item.f);
      if (item.e && item.e < item.t) badTime.push(day.id + ": " + item.title);
      if (i && item.t < day.items[i - 1].t)
        badTime.push(day.id + ": " + item.title + " out of order");
    });
  });
  check("every item floor exists in FLOORS", badFloor.length === 0, badFloor.join(", "));
  check("item times ordered and well-formed", badTime.length === 0, badTime.join(", "));
}

/* ---- 4. document structure ---- */
// selector position only, so `:#eceef2` colour literals are not read as ids
const idSelectors = new Set(
  [...css.matchAll(/(?:^|[\s,>+~])#([a-zA-Z][\w-]*)/gm)].map(m => m[1]));
const idsPresent = new Set(
  [...html.matchAll(/\bid="([a-zA-Z][\w-]*)"/g)].map(m => m[1]));
const deadIds = [...idSelectors].filter(i => !idsPresent.has(i));
check("no dead CSS id rules", deadIds.length === 0, deadIds.join(", "));

check("document closes", /<\/body>\s*<\/html>$/.test(html.trimEnd()));
const count = re => (html.match(re) || []).length;
check("tags balance",
  count(/<style>/g) === count(/<\/style>/g) &&
  count(/<script>/g) === count(/<\/script>/g) &&
  count(/<body>/g) === count(/<\/body>/g));

/* ---- 5. offline guarantee ---- */
const external = [...html.matchAll(/(?:src|href)="(https?:\/\/[^"]*)"/g)].map(m => m[1]);
check("no external resource URLs", external.length === 0, external.join(", "));

console.log("\n" + Buffer.byteLength(html) + " bytes");
process.exit(failures ? 1 : 0);
